"""
Enhanced Email Service for Divine Bridge
Sends combined daily verse + prayer emails with timezone-aware delivery
"""
import html
import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from email.mime.image import MIMEImage
from email.utils import formataddr
import logging
import os
from datetime import datetime
from pathlib import Path
from backend.core.config import get_config

logger = logging.getLogger(__name__)

# Repository root: backend/services/email/email_service_v2.py → parents[3]
_REPO_ROOT = Path(__file__).resolve().parents[3]

# Fallback when prayer JSON has no `email_intro` (AI generation failed or old data).
_DEFAULT_WEEKLY_EMAIL_INTRO = (
    "Wherever this week finds you, we are glad you are walking with us. "
    "We are holding the world’s joys and sorrows before God together—asking for comfort, courage, and peace—and we invite you to join your heart with ours in prayer."
)


class EnhancedEmailService:
    """Email service for sending daily verse and prayer emails"""

    def __init__(self):
        """Initialize email service with blessings@divinebridge.io"""
        try:
            config = get_config()

            # Check for test/dev email credentials first (for local testing)
            test_email = os.getenv("TEST_EMAIL_USER")
            test_password = os.getenv("TEST_EMAIL_PASSWORD")

            if test_email and test_password:
                # Use test credentials for local development
                self.sender_email = test_email
                self.sender_password = test_password
                logger.info(f"Using TEST email credentials: {self.sender_email}")
            else:
                # Use production credentials (blessings@divinebridge.io)
                self.sender_email = os.getenv("PRODUCTION_EMAIL_USER", "blessings@divinebridge.io")
                self.sender_password = config.email_password
                logger.info(f"Using PRODUCTION email credentials: {self.sender_email}")

            self.smtp_server = os.getenv("SMTP_SERVER", "smtp.gmail.com")
            self.smtp_port = int(os.getenv("SMTP_PORT", "587"))

            if not self.sender_password:
                raise ValueError("Email password not configured")

            logger.info("Enhanced EmailService initialized successfully")
        except Exception as e:
            logger.error(f"Error initializing EnhancedEmailService: {e}")
            raise

    def send_daily_content(self, recipient_email, first_name, verse_data, prayer_data, timezone="UTC"):
        """
        Send combined daily verse and prayer email

        Args:
            recipient_email: Subscriber's email
            first_name: Subscriber's first name
            verse_data: Dict with 'reference', 'text'
            prayer_data: Dict with 'content', 'date'; optional 'email_intro' (or
                legacy 'weekly_email_intro') — one paragraph for the weekly email body
                (normally generated by PrayerGenerator with Perplexity and stored on the prayer JSON)
            timezone: Subscriber's timezone (e.g., 'America/New_York')

        Returns:
            bool: True if sent successfully
        """
        try:
            # Format date based on timezone
            now = datetime.now()
            date_str = now.strftime("%A, %B %d, %Y")

            # Create message with related for embedded images
            msg = MIMEMultipart("related")
            msg["From"] = formataddr(("Divine Bridge", self.sender_email))
            msg["To"] = recipient_email
            msg["Subject"] = f"Your Blessings - {date_str}"

            # Email headers for deliverability
            msg["List-Unsubscribe"] = f"<https://divinebridge.io/unsubscribe?email={recipient_email}>"
            msg["List-Unsubscribe-Post"] = "List-Unsubscribe=One-Click"
            msg["Precedence"] = "bulk"

            # Create alternative part for text/html
            msg_alternative = MIMEMultipart("alternative")
            msg.attach(msg_alternative)

            intro = self._weekly_email_intro_paragraph(prayer_data)

            # Plain text version
            plain_text = self._create_plain_text(
                first_name, date_str, verse_data, prayer_data, recipient_email, intro_paragraph=intro
            )

            # HTML — Easter-inspired weekly layout (templates/emails/weekly-blessings.html)
            html_body = self._create_weekly_blessings_html(
                first_name, date_str, verse_data, prayer_data, recipient_email, intro_paragraph=intro
            )

            # Attach both versions to alternative
            msg_alternative.attach(MIMEText(plain_text, "plain", "utf-8"))
            msg_alternative.attach(MIMEText(html_body, "html", "utf-8"))

            # Attach logo as embedded image
            try:
                pass

                logo_path = str(_REPO_ROOT / "assets" / "logos" / "LogoOnly1.png")

                with open(logo_path, "rb") as img:
                    from email.mime.image import MIMEImage

                    img_data = MIMEImage(img.read())
                    img_data.add_header("Content-ID", "<logo_image>")
                    img_data.add_header("Content-Disposition", "inline", filename="logo.png")
                    msg.attach(img_data)
            except Exception as e:
                logger.warning(f"Could not attach logo: {e}")

            # Send email
            with smtplib.SMTP(self.smtp_server, self.smtp_port) as server:
                server.starttls()
                server.login(self.sender_email, self.sender_password)
                server.send_message(msg)

            logger.info(f"Daily content email sent to: {recipient_email}")
            return True

        except Exception as e:
            logger.error(f"Error sending daily email to {recipient_email}: {e}")
            return False

    @staticmethod
    def _weekly_email_intro_paragraph(prayer_data):
        raw = (prayer_data or {}).get("email_intro") or (prayer_data or {}).get("weekly_email_intro")
        if raw is not None and str(raw).strip():
            return str(raw).strip()
        return _DEFAULT_WEEKLY_EMAIL_INTRO

    def _create_weekly_blessings_html(
        self, first_name, date_str, verse_data, prayer_data, recipient_email, intro_paragraph
    ):
        """Load weekly-blessings.html and substitute escaped placeholders."""
        template_path = str(_REPO_ROOT / "web" / "templates" / "emails" / "weekly-blessings.html")
        with open(template_path, "r", encoding="utf-8") as f:
            body = f.read()

        verse_text = verse_data.get("text", "") or verse_data.get("verse", "")
        prayer_content = prayer_data.get("content", "") or ""
        prayer_html = html.escape(prayer_content).replace("\n", "<br>\n")

        unsubscribe_url = f"https://divinebridge.io/unsubscribe?email={recipient_email}"

        replacements = {
            "date_str": html.escape(date_str, quote=True),
            "first_name": html.escape(first_name or "", quote=True),
            "intro_paragraph": html.escape(intro_paragraph or "", quote=True),
            "verse_reference": html.escape(verse_data.get("reference", ""), quote=True),
            "verse_text": html.escape(verse_text, quote=True),
            "prayer_html": prayer_html,
            "unsubscribe_url": html.escape(unsubscribe_url, quote=True),
        }
        for key, val in replacements.items():
            body = body.replace("{{" + key + "}}", val)
        return body

